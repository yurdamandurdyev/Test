#!/usr/bin/env python3
"""Generate the independent assignment CLI from the SAME tested analytics source."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
core = (root / "backend/sales_intelligence/analytics.py").read_text()
cli = (root / "scripts/analyze_leads.py").read_text()
cli = cli.replace('sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))\n', "")
cli = cli.replace("from sales_intelligence.analytics import InputError, analyze, export_csv, summary_text\n", "")
cli = cli.replace("        from sales_intelligence.analytics import MAX_BYTES\n", "")
target = root / "deliverables/02-analyze-leads.py"
target.write_text("#!/usr/bin/env python3\n# Generated by scripts/build_standalone.py; edit backend source, not this release file.\n" + core + "\n" + cli)
target.chmod(0o755)
print("Generated deliverables/02-analyze-leads.py")
